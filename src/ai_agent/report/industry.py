def industry_of(subjects: list[str]) -> str:
    """主体名含「银行」即按银行模板；多主体时只要有一个银行就按银行模板。"""
    if any("银行" in (name or "") for name in subjects):
        return BANK
    return GENERIC


def default_indicators(industry: str) -> list[str]:
    return list(_BANK_INDICATORS if industry == BANK else _GENERIC_INDICATORS)


def normalize_indicator(text: str) -> str:
    """把需求里的简称归一到报表正式指标名；不认识就原样返回。"""
    cleaned = (text or "").strip()
    for alias, canonical in _ALIASES:
        if alias in cleaned:
            return canonical
    return cleaned


def indicator_aliases() -> tuple[tuple[str, str], ...]:
    return _ALIASES
