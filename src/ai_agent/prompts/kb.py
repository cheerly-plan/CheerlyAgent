def build_rerank_user(query: str, listing: str, top_k: int) -> str:
    return render(
        RERANK_TEMPLATE,
        QUERY=query,
        LISTING=listing,
        TOP_K=str(top_k),
    )


def build_align_user(count: int, pairs: str) -> str:
    return render(ALIGN_USER_TEMPLATE, COUNT=str(count), PAIRS=pairs)


def build_graph_head(title: str, span: str, section: str = "") -> str:
    """图谱抽取的批次开头：文档名 + 段号/页码定位（+ 整批同节时的节名）。"""
    if title:
        head = render(GRAPH_HEAD_WITH_DOC, TITLE=title, SPAN=span)
    else:
        head = render(GRAPH_HEAD_NO_DOC, SPAN=span)
    if section:
        head += render(GRAPH_SECTION_SUFFIX, SECTION=section)
    return head + GRAPH_HEAD_TAIL
